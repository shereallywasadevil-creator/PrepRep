PANTRY = "You'll also need salt, black pepper, water and a little cooking oil or spray."


def guide_for(recipe):
    """The full guide for one recipe dict from build_recipes, with shared text filled in."""
    g = GUIDES.get(recipe["id"])
    if not g:
        return None
    kind = g.get("protein") or {"chicken": "chicken", "turkey": "turkey", "red meat": "red meat", "seafood": "seafood"}.get(recipe.get("protein_type"), "plant")
    return {"pantry": PANTRY, "tools": g["tools"], "prep": g["prep"], "steps": g["steps"], "tips": g.get("tips", []),
            "safe": g.get("safe", SAFE[kind]), "store": g.get("store", STORE), "reheat": g.get("reheat", REHEAT)}


